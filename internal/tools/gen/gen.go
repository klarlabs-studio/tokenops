// Package gen holds the code generators behind `go generate ./...`: the
// list of provider descriptors and account readers (listgen), and the docs
// tables and menu-bar names derived from the provider registry
// (providerdocs). Each generator's output is checked in, and a test fails
// when it is stale, so a reviewer sees exactly what a change generates.
package gen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// List is one generated slice: every top-level function in a package whose
// name starts with Prefix and that returns Type, called in file-name order.
type List struct {
	// Var is the generated variable's name.
	Var string
	// Prefix is the functions' name prefix ("provider", "reader").
	Prefix string
	// Type is the functions' result type as written in the source
	// ("Descriptor", "usage.Reader").
	Type string
}

// ParseList reads "var=prefix:Type".
func ParseList(s string) (List, error) {
	v, rest, ok := strings.Cut(s, "=")
	if !ok {
		return List{}, fmt.Errorf("list %q: want var=prefix:Type", s)
	}
	p, t, ok := strings.Cut(rest, ":")
	if !ok || v == "" || p == "" || t == "" {
		return List{}, fmt.Errorf("list %q: want var=prefix:Type", s)
	}
	return List{Var: v, Prefix: p, Type: t}, nil
}

// ListFile renders the generated file for the package in dir. Imports are
// copied from the source files that declare the listed types' packages, so
// "usage.Reader" brings its import along.
func ListFile(dir, out string, lists []List) ([]byte, error) {
	fset := token.NewFileSet()
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	sort.Strings(names)
	pkg := ""
	found := make([][]string, len(lists))
	imports := map[string]string{} // name -> path
	for _, name := range names {
		base := filepath.Base(name)
		if base == out || strings.HasSuffix(base, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		pkg = f.Name.Name
		fileImports := map[string]string{}
		for _, imp := range f.Imports {
			path := strings.Trim(imp.Path.Value, `"`)
			n := filepath.Base(path)
			if imp.Name != nil {
				n = imp.Name.Name
			}
			fileImports[n] = path
		}
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || fn.Type.Params.NumFields() != 0 || fn.Type.Results.NumFields() != 1 {
				continue
			}
			result := exprString(fn.Type.Results.List[0].Type)
			for i, l := range lists {
				if !strings.HasPrefix(fn.Name.Name, l.Prefix) || len(fn.Name.Name) == len(l.Prefix) || result != l.Type {
					continue
				}
				found[i] = append(found[i], fn.Name.Name)
				if q, _, ok := strings.Cut(l.Type, "."); ok {
					imports[q] = fileImports[q]
				}
			}
		}
	}
	if pkg == "" {
		return nil, fmt.Errorf("no Go files in %s", dir)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/tools/gen/listgen; DO NOT EDIT.\n\npackage %s\n\n", pkg)
	if len(imports) > 0 {
		b.WriteString("import (\n")
		qs := make([]string, 0, len(imports))
		for q := range imports {
			qs = append(qs, q)
		}
		sort.Strings(qs)
		for _, q := range qs {
			if filepath.Base(imports[q]) == q {
				fmt.Fprintf(&b, "\t%q\n", imports[q])
			} else {
				fmt.Fprintf(&b, "\t%s %q\n", q, imports[q])
			}
		}
		b.WriteString(")\n\n")
	}
	for i, l := range lists {
		fmt.Fprintf(&b, "// %s is every %s*() function in this package, by file name.\n", l.Var, l.Prefix)
		fmt.Fprintf(&b, "var %s = []func() %s{\n", l.Var, l.Type)
		for _, fn := range found[i] {
			fmt.Fprintf(&b, "\t%s,\n", fn)
		}
		b.WriteString("}\n\n")
	}
	return format.Source(bytes.TrimRight(b.Bytes(), "\n"))
}

func exprString(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		return exprString(t.X) + "." + t.Sel.Name
	}
	return ""
}

// WriteIfChanged writes b to path when its content differs.
func WriteIfChanged(path string, b []byte) error {
	if cur, err := os.ReadFile(path); err == nil && bytes.Equal(cur, b) {
		return nil
	}
	return os.WriteFile(path, b, 0o644)
}

// ReplaceRegion replaces the text between the marker comments
// "<!-- begin generated: name -->" and "<!-- end generated: name -->" in doc
// with body, keeping the markers.
func ReplaceRegion(doc []byte, name, body string) ([]byte, error) {
	begin := []byte(BeginMarker(name))
	end := []byte(EndMarker(name))
	i := bytes.Index(doc, begin)
	j := bytes.Index(doc, end)
	if i < 0 || j < 0 || j < i {
		return nil, fmt.Errorf("markers for %q not found", name)
	}
	var out bytes.Buffer
	out.Write(doc[:i+len(begin)])
	out.WriteString("\n")
	out.WriteString(strings.TrimRight(body, "\n"))
	out.WriteString("\n")
	out.Write(doc[j:])
	return out.Bytes(), nil
}

// BeginMarker and EndMarker delimit a generated region in a Markdown file.
func BeginMarker(name string) string { return "<!-- begin generated: " + name + " -->" }

// EndMarker ends a generated region.
func EndMarker(name string) string { return "<!-- end generated: " + name + " -->" }
